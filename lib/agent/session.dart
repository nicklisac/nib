import 'dart:convert';
import 'dart:io';
import 'package:path/path.dart' as p;
import '../ai/chat_message.dart';
import 'skills.dart';

/// Manages the conversation transcript, system prompt, persistence, and turns.
class AgentSession {
  final String id;
  String systemPrompt;
  final List<ChatMessage> _messages = [];

  /// Current prompt tokens for the active transcript (from latest provider response).
  int currentPromptTokens = 0;

  /// Cached prompt tokens for the active transcript (from latest provider response).
  int cachedPromptTokens = 0;

  /// Cumulative completion tokens generated by the model across this session.
  int totalCompletionTokens = 0;

  /// Cumulative prompt tokens billed/processed across all turns in this session.
  int cumulativePromptTokens = 0;

  /// Cumulative cached prompt tokens across all turns in this session.
  int cumulativeCachedTokens = 0;

  /// Number of tool calls executed during this session.
  int toolExecutionsCount = 0;

  /// Retained for backwards compatibility: returns current active prompt tokens.
  int get totalPromptTokens => currentPromptTokens;
  set totalPromptTokens(int val) {
    currentPromptTokens = val;
    cumulativePromptTokens = val;
  }

  AgentSession({String? id, String? systemPrompt, String? workspacePath})
    : id = id ?? 'session_${DateTime.now().millisecondsSinceEpoch}',
      systemPrompt =
          systemPrompt ??
          buildDefaultSystemPrompt(workspacePath: workspacePath);

  List<ChatMessage> get messages => List.unmodifiable(_messages);

  /// True if the session has at least one user message recorded.
  bool get hasUserMessages => _messages.any((m) => m.role == Role.user);

  void addMessage(ChatMessage message) {
    _messages.add(message);
  }

  /// Creates a fresh session initialized with current system prompt and workspace.
  factory AgentSession.createNew({
    String? id,
    String? basePrompt,
    String? appendPrompt,
    String? workspacePath,
  }) {
    final session = AgentSession(id: id, workspacePath: workspacePath);
    session.rebuildSystemPrompt(
      basePrompt: basePrompt,
      appendPrompt: appendPrompt,
      workspacePath: workspacePath,
    );
    return session;
  }

  void addSystemPromptIfNeeded() {
    if (_messages.isEmpty || _messages.first.role != Role.system) {
      _messages.insert(0, ChatMessage.system(systemPrompt));
    } else {
      _messages[0] = ChatMessage.system(systemPrompt);
    }
  }

  void clearMessages() {
    _messages.clear();
  }

  void clearHistory() {
    _messages.clear();
    currentPromptTokens = 0;
    cachedPromptTokens = 0;
    cumulativePromptTokens = 0;
    cumulativeCachedTokens = 0;
    totalCompletionTokens = 0;
    toolExecutionsCount = 0;
    addSystemPromptIfNeeded();
  }

  void recordUsage(
    int? promptTokens,
    int? completionTokens, {
    int? cachedTokens,
  }) {
    if (promptTokens != null) {
      currentPromptTokens = promptTokens;
      cumulativePromptTokens += promptTokens;
    }
    if (cachedTokens != null) {
      cachedPromptTokens = cachedTokens;
      cumulativeCachedTokens += cachedTokens;
    }
    if (completionTokens != null) {
      totalCompletionTokens += completionTokens;
    }
  }

  void rebuildSystemPrompt({
    String? basePrompt,
    String? appendPrompt,
    String? workspacePath,
  }) {
    final base = (basePrompt ?? _defaultSystemPrompt).trimRight();
    final skillsPrompt = SkillsManager.instance.formatForSystemPrompt();
    final append = (appendPrompt != null && appendPrompt.isNotEmpty)
        ? '\n\n$appendPrompt'
        : '';
    final cwd = workspacePath ?? Directory.current.path;
    final now = DateTime.now();
    final dateStr =
        '${now.year.toString().padLeft(4, '0')}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
    final runtimeInfo =
        '\n\nCurrent date: $dateStr\nCurrent working directory: $cwd';

    systemPrompt = '$base$skillsPrompt$append$runtimeInfo';
    addSystemPromptIfNeeded();
  }

  /// Optional override for the session storage directory (primarily for testing).
  static String? storageDirectoryOverride;

  /// Global switch: if false, session disk saving is completely bypassed (useful in tests).
  static bool enableDiskPersistence = true;

  /// Automatically persists session transcript to `~/.nib/sessions/<id>.jsonl`
  static String? get _defaultStorageDirectory {
    final home =
        Platform.environment['HOME'] ??
        Platform.environment['USERPROFILE'] ??
        '';
    return home.isNotEmpty ? p.join(home, '.nib', 'sessions') : null;
  }

  Future<void> saveToDisk() async {
    if (!enableDiskPersistence) return;
    try {
      final String? sessionDirPath =
          storageDirectoryOverride ?? _defaultStorageDirectory;
      if (sessionDirPath == null) return;

      final sessionDir = Directory(sessionDirPath);
      if (!await sessionDir.exists()) {
        await sessionDir.create(recursive: true);
      }

      final file = File(p.join(sessionDir.path, '$id.jsonl'));
      final sink = file.openWrite();

      // Write metadata header
      sink.writeln(
        jsonEncode({
          '_type': 'meta',
          'id': id,
          'system_prompt': systemPrompt,
          'current_prompt_tokens': currentPromptTokens,
          'prompt_tokens': currentPromptTokens,
          'cached_prompt_tokens': cachedPromptTokens,
          'cumulative_prompt_tokens': cumulativePromptTokens,
          'cumulative_cached_tokens': cumulativeCachedTokens,
          'completion_tokens': totalCompletionTokens,
          'tool_executions': toolExecutionsCount,
          'timestamp': DateTime.now().toIso8601String(),
        }),
      );

      // Write messages
      for (final msg in _messages) {
        sink.writeln(jsonEncode(msg.toJson()));
      }

      await sink.flush();
      await sink.close();
    } catch (_) {}
  }

  /// Loads a session from disk by its ID from `~/.nib/sessions/`.
  static Future<AgentSession?> loadFromDisk(String id) async {
    try {
      File? file;
      if (storageDirectoryOverride != null) {
        final overrideFile = File(
          p.join(storageDirectoryOverride!, '$id.jsonl'),
        );
        if (await overrideFile.exists()) {
          file = overrideFile;
        }
      }

      if (file == null) {
        final storageDir = _defaultStorageDirectory;
        if (storageDir == null) return null;

        final candidate = File(p.join(storageDir, '$id.jsonl'));
        if (!await candidate.exists()) return null;
        file = candidate;
      }

      final lines = await file.readAsLines();
      if (lines.isEmpty) return null;

      AgentSession? session;

      for (final line in lines) {
        if (line.trim().isEmpty) continue;
        final json = jsonDecode(line) as Map<String, dynamic>;

        if (json['_type'] == 'meta') {
          session = AgentSession(
            id: json['id'] as String?,
            systemPrompt: json['system_prompt'] as String?,
          );
          session.currentPromptTokens =
              json['current_prompt_tokens'] as int? ??
              json['prompt_tokens'] as int? ??
              0;
          session.cachedPromptTokens =
              json['cached_prompt_tokens'] as int? ?? 0;
          session.cumulativePromptTokens =
              json['cumulative_prompt_tokens'] as int? ??
              session.currentPromptTokens;
          session.cumulativeCachedTokens =
              json['cumulative_cached_tokens'] as int? ?? 0;
          session.totalCompletionTokens =
              json['completion_tokens'] as int? ?? 0;
          session.toolExecutionsCount = json['tool_executions'] as int? ?? 0;
        } else if (session != null) {
          session.addMessage(ChatMessage.fromJson(json));
        }
      }

      return session;
    } catch (_) {
      return null;
    }
  }

  /// Returns the most recent session ID from ~/.nib/sessions/
  static Future<String?> getMostRecentSessionId() async {
    try {
      final dirs = <Directory>[];
      final targetDir = storageDirectoryOverride ?? _defaultStorageDirectory;
      if (targetDir == null) return null;
      dirs.add(Directory(targetDir));

      final files = <File>[];
      for (final sessionDir in dirs) {
        if (await sessionDir.exists()) {
          final entities = await sessionDir.list().toList();
          files.addAll(
            entities.whereType<File>().where((f) => f.path.endsWith('.jsonl')),
          );
        }
      }
      if (files.isEmpty) return null;

      files.sort(
        (a, b) => b.lastModifiedSync().compareTo(a.lastModifiedSync()),
      );
      final mostRecent = files.first;
      return p.basenameWithoutExtension(mostRecent.path);
    } catch (_) {
      return null;
    }
  }

  /// Lists saved sessions with their date, turn count, and last prompt.
  static Future<List<Map<String, dynamic>>> listSavedSessions() async {
    final list = <Map<String, dynamic>>[];
    try {
      final dirs = <Directory>[];
      final targetDir = storageDirectoryOverride ?? _defaultStorageDirectory;
      if (targetDir == null) return list;
      dirs.add(Directory(targetDir));

      final seenIds = <String>{};
      final files = <File>[];

      for (final dir in dirs) {
        if (await dir.exists()) {
          final entities = await dir
              .list()
              .where((e) => e is File && e.path.endsWith('.jsonl'))
              .toList();
          for (final e in entities) {
            final f = e as File;
            final id = p.basenameWithoutExtension(f.path);
            if (seenIds.add(id)) {
              files.add(f);
            }
          }
        }
      }

      files.sort(
        (a, b) => b.statSync().modified.compareTo(a.statSync().modified),
      );

      for (final f in files.take(10)) {
        final id = p.basenameWithoutExtension(f.path);
        final lines = await f.readAsLines();
        String summary = '';
        int messageCount = 0;
        for (final line in lines) {
          try {
            final parsed = jsonDecode(line) as Map<String, dynamic>;
            if (parsed['role'] == 'user') {
              summary = (parsed['content'] as String? ?? '').replaceAll(
                '\n',
                ' ',
              );
              messageCount++;
            }
          } catch (_) {}
        }
        list.add({
          'id': id,
          'modified': f.statSync().modified,
          'user_turns': messageCount,
          'last_prompt': summary.length > 50
              ? '${summary.substring(0, 47)}...'
              : summary,
        });
      }
    } catch (_) {}
    return list;
  }

  static String buildDefaultSystemPrompt({String? workspacePath}) {
    final cwd = workspacePath ?? Directory.current.path;
    final now = DateTime.now();
    final dateStr =
        '${now.year.toString().padLeft(4, '0')}-${now.month.toString().padLeft(2, '0')}-${now.day.toString().padLeft(2, '0')}';
    return '$_defaultSystemPrompt\n\nCurrent date: $dateStr\nCurrent working directory: $cwd';
  }

  static const String _defaultSystemPrompt = '''
